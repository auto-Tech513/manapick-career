export function typeCodeFromScores(scores: Record<WorkstyleAxisKey, number>): string {
  return workstyleAxes.map((axis) => (scores[axis.key] >= 0 ? axis.plusLetter : axis.minusLetter)).join("");
}

export function axisStrength(score: number): "はっきり" | "わずかに" {
  return Math.abs(score) >= 3 ? "はっきり" : "わずかに";
}
